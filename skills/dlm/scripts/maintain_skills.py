#!/usr/bin/env python3
"""Keep the dlm skill suite complete and in step with the dlm binary.

For contributors to dlm; agents using dlm do not need this.

    maintain_skills.py generate    rewrite references/cli.md and rest-api.md
    maintain_skills.py check       fail on anything the suite no longer covers

`check` proves completeness: every command, REST operation, setting, config key,
event, task error code and API problem code of dlm must appear in the suite, the
generated files must be current, each SKILL.md must meet the Agent Skills
specification and links must resolve.

Run from a dlm-server checkout. --dlm picks the binary (default: `go run ./cmd/dlm`).
A daemon is started in a temporary directory to read the live config keys.
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
SUITE = ("dlm", "dlm-organize", "dlm-sources", "dlm-admin")
SOURCE = REPO / "skills"
GENERATED = "<!-- Generated by scripts/maintain_skills.py from the dlm binary. Do not edit. -->\n"
MAX_DESCRIPTION = 1024
MAX_LINES = 500
HIDDEN_COMMANDS = {"dlm", "dlm docs", "dlm help", "dlm completion"}


def output(dlm: list[str], *args: str) -> str:
    """Return the standard output of a dlm command."""
    return subprocess.run([*dlm, *args], capture_output=True, text=True, check=True, cwd=REPO).stdout


def command_sections(docs: str) -> list[tuple[str, str]]:
    """Split `dlm docs` into (command, body) sections."""
    parts = re.split(r"(?m)^## (?=dlm)", docs)[1:]
    return [(part.split("\n", 1)[0].strip(), part.split("\n", 1)[1]) for part in parts]


def compact_section(body: str) -> str:
    """Drop what repeats in every section of the generated command reference."""
    body = re.sub(r"(?ms)^### Options inherited from parent commands.*?(?=^### |\Z)", "", body)
    body = re.sub(r"(?ms)^### SEE ALSO.*\Z", "", body)
    body = re.sub(r"\n\s*-h, --help[^\n]*", "", body)
    body = re.sub(r"(?m)^### Options\n+```\n*```\n*", "", body)
    return re.sub(r"(?m)^### ", "#### ", body).strip()


def render_cli(docs: str) -> str:
    """Render references/cli.md."""
    sections = command_sections(docs)
    root = dict(sections)["dlm"]
    groups: dict[str, list[tuple[str, str]]] = {}
    for name, body in sections:
        if name != "dlm":
            groups.setdefault(name.split()[1], []).append((name, body))
    lines = [
        "# dlm command reference\n", GENERATED,
        "Every command and its own flags. These global flags work on all of them:\n",
        compact_section("### Options" + root.split("### Options", 1)[1]),
        "\n## Contents\n",
    ]
    lines += [f"- [dlm {group}](#dlm-{group})" for group in groups]
    for group, commands in groups.items():
        lines.append(f"\n## dlm {group}\n")
        for name, body in commands:
            if name != f"dlm {group}":
                lines.append(f"### {name}\n")
            lines.append(compact_section(body) + "\n")
    return "\n".join(lines).rstrip() + "\n"


def render_rest(spec: dict[str, Any]) -> str:
    """Render references/rest-api.md."""
    lines = [
        "# REST operations\n", GENERATED,
        "All operations of the daemon, grouped by resource. The operation ID is also",
        "the name in `dlm openapi`, where the full request and response schemas are.\n",
    ]
    groups: dict[str, list[tuple[str, str, str, str]]] = {}
    for path, operations in spec["paths"].items():
        for method, op in operations.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            group = path.split("/")[2] if path.startswith("/v1/") else "other"
            groups.setdefault(group, []).append((method.upper(), path, op["operationId"], op.get("summary", "")))
    for group in sorted(groups):
        lines += [f"## {group}\n", "| Method | Path | Operation | Summary |", "|---|---|---|---|"]
        lines += [f"| {m} | `{p}` | `{o}` | {s} |" for m, p, o, s in sorted(groups[group], key=lambda r: (r[1], r[0]))]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_generated(dlm: list[str]) -> None:
    """Rewrite the generated references."""
    references = SOURCE / "dlm" / "references"
    references.mkdir(exist_ok=True)
    (references / "cli.md").write_text(render_cli(output(dlm, "docs")))
    (references / "rest-api.md").write_text(render_rest(json.loads(output(dlm, "openapi"))))


def settings_paths(spec: dict[str, Any]) -> set[str]:
    """Return every leaf setting path of the OpenAPI Settings schema."""
    schemas = spec["components"]["schemas"]
    paths: set[str] = set()
    for key, value in schemas["Settings"]["properties"].items():
        if key == "$schema":
            continue
        ref = value.get("$ref", "").rsplit("/", 1)[-1]
        if ref in ("RefreshSettings", "RetrySettings", "TorrentSettings"):
            paths |= {f"{key}.{sub}" for sub in schemas[ref]["properties"] if sub != "$schema"}
        else:
            paths.add(key)
    return paths


def live_config_keys(dlm: list[str]) -> set[str]:
    """Return the boot config keys of a throwaway daemon."""
    with tempfile.TemporaryDirectory() as home:
        cli = [*dlm, "--home", home]
        daemon = subprocess.Popen([*cli, "serve", "--address", "127.0.0.1:0"], cwd=REPO, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)  # noqa: S603
        try:
            for _ in range(100):
                probe = subprocess.run([*cli, "config", "get", "-o", "json"], capture_output=True, text=True, check=False, cwd=REPO)
                if probe.returncode == 0:
                    return {entry["key"] for entry in json.loads(probe.stdout)["entries"]}
                time.sleep(0.2)
            raise RuntimeError("the throwaway daemon did not start")
        finally:
            daemon.terminate()
            daemon.wait(timeout=15)


def problem_codes() -> set[str]:
    """Return the API problem codes used in the Go source."""
    codes: set[str] = set()
    pattern = re.compile(r'"([a-z_]+\.[a-z_]+)"')
    calls = re.compile(r"(?:NotFoundCode|ConflictCode|InvalidArgumentCode|PreconditionFailedCode|[Pp]roblem\w*|[Cc]ode:?|[Ff]orbidden\w*)\(?[^\n]*")
    for path in (REPO / "internal").rglob("*.go"):
        if path.name.endswith("_test.go"):
            continue
        for line in path.read_text().splitlines():
            if calls.search(line):
                codes |= {c for c in pattern.findall(line) if c.split(".")[0] in KNOWN_AREAS}
    return codes


KNOWN_AREAS = {
    "auth", "browser", "capture", "cleanup", "config", "fs", "limits", "native_host", "origin",
    "pairing", "queue", "request", "service", "settings", "stats", "task", "token", "torrent",
}


def frontmatter(text: str) -> dict[str, str]:
    """Return the top-level scalar fields of a SKILL.md frontmatter."""
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        return {}
    return dict(re.findall(r"(?m)^([a-z-]+): (.+)$", match.group(1)))


def check_skills(problems: list[str]) -> None:
    """Check the format of each skill and its links."""
    for name in SUITE:
        path = SOURCE / name / "SKILL.md"
        text = path.read_text()
        meta = frontmatter(text)
        if meta.get("name") != name:
            problems.append(f"{name}: frontmatter name does not match the directory")
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name):
            problems.append(f"{name}: invalid skill name")
        if not 0 < len(meta.get("description", "")) <= MAX_DESCRIPTION:
            problems.append(f"{name}: description must be 1-{MAX_DESCRIPTION} characters, is {len(meta.get('description', ''))}")
        if len(text.splitlines()) >= MAX_LINES:
            problems.append(f"{name}: SKILL.md has {MAX_LINES} lines or more")
        for doc in (SOURCE / name).rglob("*.md"):
            for link in re.findall(r"\]\((?!https?:|#)([^)]+)\)", doc.read_text()):
                if not (doc.parent / link.split("#")[0]).exists():
                    problems.append(f"{doc.relative_to(SOURCE)}: broken link {link}")


def covered_text() -> str:
    """Return everything the suite says, except the generated references."""
    parts = []
    for name in SUITE:
        for doc in (SOURCE / name).rglob("*.md"):
            parts.append(doc.read_text())
    return "\n".join(parts)


def check(dlm: list[str]) -> int:
    """Report everything the suite fails to cover."""
    docs = output(dlm, "docs")
    spec = json.loads(output(dlm, "openapi"))
    problems: list[str] = []
    check_skills(problems)

    references = SOURCE / "dlm" / "references"
    if (references / "cli.md").read_text() != render_cli(docs):
        problems.append("references/cli.md is stale; run generate")
    if (references / "rest-api.md").read_text() != render_rest(spec):
        problems.append("references/rest-api.md is stale; run generate")

    text = covered_text()
    handwritten = "\n".join(
        doc.read_text() for name in SUITE for doc in (SOURCE / name).rglob("*.md")
        if doc.name not in ("cli.md", "rest-api.md")
    )

    groups: dict[str, list[str]] = {}
    commands = [name for name, _ in command_sections(docs) if name not in HIDDEN_COMMANDS]
    groups["commands (reference)"] = [c for c in commands if f"### {c}\n" not in text and f"## {c}\n" not in text]
    top = sorted({" ".join(c.split()[:2]) for c in commands})
    groups["command groups (explained in a skill)"] = [c for c in top if c not in handwritten]

    operations = [op["operationId"] for ops in spec["paths"].values() for m, op in ops.items() if m in ("get", "post", "put", "patch", "delete")]
    groups["REST operations"] = [o for o in operations if f"`{o}`" not in text]
    groups["settings"] = sorted(s for s in settings_paths(spec) if f"`{s}`" not in handwritten)
    groups["config keys"] = sorted(k for k in live_config_keys(dlm) if f"`{k}`" not in handwritten and f"{k}`" not in handwritten)
    events = spec["components"]["schemas"]["StreamEvent"]["discriminator"]["mapping"]
    groups["events"] = sorted(e for e in events if f"`{e}`" not in handwritten)
    domain = (REPO / "internal" / "domain" / "task.go").read_text()
    task_codes = re.findall(r'ErrorCode\w+ = "(\w+)"', domain)
    groups["task error codes"] = sorted(c for c in task_codes if f"`{c}`" not in handwritten)
    groups["API problem codes"] = sorted(c for c in problem_codes() if f"`{c}`" not in handwritten)

    print(f"checked {len(commands)} commands, {len(operations)} operations, {len(settings_paths(spec))} settings, "
          f"{len(events)} events, {len(task_codes)} task error codes")
    for label, missing in groups.items():
        if missing:
            problems.append(f"not covered, {label}: {', '.join(missing)}")
    for problem in problems:
        print("FAIL", problem)
    if not problems:
        print("OK: the suite covers all of dlm")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("action", choices=("generate", "check"))
    parser.add_argument("--dlm", default="go run ./cmd/dlm", help="how to run dlm from the checkout")
    args = parser.parse_args()
    dlm = shlex.split(args.dlm)
    if args.action == "generate":
        write_generated(dlm)
        print("generated the references")
    return check(dlm)


if __name__ == "__main__":
    sys.exit(main())
