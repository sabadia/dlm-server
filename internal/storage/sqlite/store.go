// Package sqlite implements the storage ports on top of SQLite using the
// pure-Go modernc.org/sqlite driver (no CGO).
//
// # Connections
//
// Open creates two connection pools on the same database file:
//   - a writer pool limited to a single connection, so writes are serialised
//     inside the process and never contend for SQLite's write lock
//     (no SQLITE_BUSY between our own writers). Transactions run on it and
//     start with BEGIN IMMEDIATE, taking the write lock up front;
//   - a reader pool with several query-only connections. In WAL mode
//     readers never block the writer and see the last committed state.
//
// # Representation
//
// Timestamps are stored as INTEGER Unix milliseconds in UTC, so domain times
// read back are truncated to the millisecond and are in UTC. Settings,
// Source, Resource, labels and task errors are stored as JSON text.
//
// Queries are generated by sqlc into package db (run `go generate` after
// editing queries/*.sql or migrations/*.sql); only the dynamic task listing
// is built by hand, always with bound parameters.
package sqlite

//go:generate sqlc generate

