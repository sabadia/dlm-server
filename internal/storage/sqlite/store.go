//go:embed migrations/*.sql
var migrationsFS embed.FS

// Options configures Open. Zero values select defaults.
type Options struct {
	// Logger receives migration and lifecycle logs; nil discards them.
	Logger *slog.Logger
	// Clock supplies the current time for storage-maintained timestamps;
	// nil means time.Now.
	Clock func() time.Time
}

// Store is the SQLite implementation of storage.Store. A Store returned by
// Open owns the connection pools; the Store passed to a WithTx callback is
// bound to that transaction.
type Store struct {
	writer *sql.DB
	reader *sql.DB
	tx     *sql.Tx
	log    *slog.Logger
	now    func() time.Time
}

var _ storage.Store = (*Store)(nil)

const busyTimeoutMillis = 5000

// Open opens (creating if needed) the database at path, applies pending
// migrations and makes sure the built-in Main queue exists.
func Open(ctx context.Context, path string, opts Options) (*Store, error) {
	if path == "" || strings.ContainsRune(path, '?') {
		return nil, domain.InvalidArgument("storage: invalid database path %q", path)
	}
	s := &Store{log: opts.Logger, now: opts.Clock}
	if s.log == nil {
		s.log = slog.New(slog.DiscardHandler)
	}
	if s.now == nil {
		s.now = time.Now
	}

	writer, err := openPool(ctx, path, url.Values{
		"_pragma": {
			fmt.Sprintf("busy_timeout(%d)", busyTimeoutMillis),
			"journal_mode(WAL)",
			"foreign_keys(ON)",
			"synchronous(NORMAL)",
		},
		"_txlock": {"immediate"},
	})
	if err != nil {
		return nil, err
	}
	writer.SetMaxOpenConns(1)
	writer.SetMaxIdleConns(1)
	writer.SetConnMaxLifetime(0)
	writer.SetConnMaxIdleTime(0)
	s.writer = writer

	if err := s.migrate(ctx); err != nil {
		return nil, errors.Join(err, s.Close())
	}

	// The reader pool is opened after the writer switched the file to WAL;
	// journal_mode is persistent, so readers need not (and, being query-only,
	// could not) set it.
	reader, err := openPool(ctx, path, url.Values{
		"_pragma": {
			fmt.Sprintf("busy_timeout(%d)", busyTimeoutMillis),
			"foreign_keys(ON)",
			"query_only(ON)",
		},
	})
	if err != nil {
		return nil, errors.Join(err, s.Close())
	}
	n := max(4, runtime.GOMAXPROCS(0))
	reader.SetMaxOpenConns(n)
	reader.SetMaxIdleConns(n)
	s.reader = reader

	if err := s.EnsureDefaults(ctx); err != nil {
		return nil, errors.Join(err, s.Close())
	}
	return s, nil
}

func openPool(ctx context.Context, path string, params url.Values) (*sql.DB, error) {
	pool, err := sql.Open("sqlite", path+"?"+params.Encode())
	if err != nil {
		return nil, fmt.Errorf("storage: open %q: %w", path, err)
	}
	if err := pool.PingContext(ctx); err != nil {
		return nil, errors.Join(fmt.Errorf("storage: open %q: %w", path, err), pool.Close())
	}
	return pool, nil
}

func (s *Store) migrate(ctx context.Context) error {
	fsys, err := fs.Sub(migrationsFS, "migrations")
	if err != nil {
		return fmt.Errorf("storage: migrations: %w", err)
	}
	p, err := goose.NewProvider(goose.DialectSQLite3, s.writer, fsys,
		goose.WithDisableGlobalRegistry(true),
	)
	if err != nil {
		return fmt.Errorf("storage: migrations: %w", err)
	}
	results, err := p.Up(ctx)
	if err != nil {
		return fmt.Errorf("storage: migrate: %w", err)
	}
	for _, r := range results {
		s.log.InfoContext(ctx, "storage: migration applied",
			"version", r.Source.Version, "duration", r.Duration)
	}
	return nil
}

// EnsureDefaults inserts the built-in Main queue when it is missing. It is
// called by Open and is idempotent.
func (s *Store) EnsureDefaults(ctx context.Context) error {
	return s.inTx(ctx, func(tx *Store) error {
		_, err := tx.Queues().Get(ctx, domain.MainQueueID)
		if err == nil {
			return nil
		}
		if !errors.Is(err, domain.ErrNotFound) {
			return err
		}
		if err := tx.Queues().Create(ctx, domain.NewMainQueue(tx.now())); err != nil {
			return err
		}
		s.log.InfoContext(ctx, "storage: created default queue", "queue_id", domain.MainQueueID)
		return nil
	})
}

// Close closes both connection pools. It must not be called on the Store
// passed to a WithTx callback.
func (s *Store) Close() error {
	if s.tx != nil {
		return errors.New("storage: close called on a transaction-bound store")
	}
	var errs []error
	if s.reader != nil {
		if err := s.reader.Close(); err != nil {
			errs = append(errs, fmt.Errorf("storage: close reader: %w", err))
		}
	}
	if s.writer != nil {
		if err := s.writer.Close(); err != nil {
			errs = append(errs, fmt.Errorf("storage: close writer: %w", err))
		}
	}
	return errors.Join(errs...)
}

