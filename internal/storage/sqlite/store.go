// WithTx implements storage.Store.
func (s *Store) WithTx(ctx context.Context, fn func(tx storage.Store) error) error {
	return s.inTx(ctx, func(tx *Store) error { return fn(tx) })
}

// inTx runs fn in a transaction on the writer pool, or directly when s is
// already bound to one.
func (s *Store) inTx(ctx context.Context, fn func(tx *Store) error) (err error) {
	if s.tx != nil {
		return fn(s)
	}
	tx, err := s.writer.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("storage: begin transaction: %w", err)
	}
	bound := &Store{writer: s.writer, reader: s.reader, tx: tx, log: s.log, now: s.now}
	committed := false
	defer func() {
		if committed {
			return
		}
		if rbErr := tx.Rollback(); rbErr != nil && !errors.Is(rbErr, sql.ErrTxDone) {
			s.log.ErrorContext(ctx, "storage: rollback failed", "error", rbErr)
			if err != nil {
				err = errors.Join(err, fmt.Errorf("storage: rollback: %w", rbErr))
			}
		}
	}()
	if err := fn(bound); err != nil {
		return err
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("storage: commit: %w", err)
	}
	committed = true
	return nil
}

// read returns the queries for read operations.
func (s *Store) read() *db.Queries {
	if s.tx != nil {
		return db.New(s.tx)
	}
	return db.New(s.reader)
}

// readConn returns the connection used for hand-written reads.
func (s *Store) readConn() db.DBTX {
	if s.tx != nil {
		return s.tx
	}
	return s.reader
}

// write returns the queries for single-statement writes.
func (s *Store) write() *db.Queries {
	if s.tx != nil {
		return db.New(s.tx)
	}
	return db.New(s.writer)
}

// sqliteCode returns the extended SQLite result code of err, or 0.
func sqliteCode(err error) int {
	var se *sqlite.Error
	if errors.As(err, &se) {
		return se.Code()
	}
	return 0
}

func isUniqueViolation(err error) bool {
	c := sqliteCode(err)
	return c == sqlite3.SQLITE_CONSTRAINT_UNIQUE || c == sqlite3.SQLITE_CONSTRAINT_PRIMARYKEY
}

func isPrimaryKeyViolation(err error) bool {
	return sqliteCode(err) == sqlite3.SQLITE_CONSTRAINT_PRIMARYKEY
}

// isForeignKeyViolation reports a foreign-key failure. SQLite reports an
// immediate ON DELETE RESTRICT failure as SQLITE_CONSTRAINT_TRIGGER (RESTRICT
// is implemented as an internal trigger); the schema defines no triggers of
// its own, so that code always means a foreign-key violation here.
func isForeignKeyViolation(err error) bool {
	c := sqliteCode(err)
	return c == sqlite3.SQLITE_CONSTRAINT_FOREIGNKEY || c == sqlite3.SQLITE_CONSTRAINT_TRIGGER
}
