package cli

import (
	"bytes"
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

func (a *app) newDocsCommand() *cobra.Command {
	return &cobra.Command{
		Use:    "docs",
		Short:  "Print the command reference as Markdown",
		Long:   "Print the reference of every command, with its flags and examples, as one Markdown document (docs/CLI.md is generated with it: make docs).",
		Hidden: true,
		Args:   cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return writeReference(cmd.OutOrStdout(), cmd.Root())
		},
	}
}

// writeReference writes the command reference of root's visible commands as
// one Markdown document: an index, then a section per command.
func writeReference(w io.Writer, root *cobra.Command) error {
	var cmds []*cobra.Command
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		// cobra adds help and completion when a command runs, so they would
		// make the output depend on how it was produced.
		if !c.IsAvailableCommand() || c.Name() == "help" || c.Name() == "completion" {
			return
		}
		cmds = append(cmds, c)
		kids := append([]*cobra.Command(nil), c.Commands()...)
		sort.Slice(kids, func(i, j int) bool { return kids[i].Name() < kids[j].Name() })
		for _, k := range kids {
			walk(k)
		}
	}
	walk(root)

	var b bytes.Buffer
	b.WriteString("# dlm command reference\n\n")
	b.WriteString("<!-- Generated by `dlm docs` (make docs). Do not edit. -->\n\n")
	b.WriteString("Every REST API operation has a command; `dlm --help` and `dlm COMMAND --help` print the same text.\n\n")
	b.WriteString("| Command | Description |\n|---|---|\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", c.CommandPath(), anchor(c.CommandPath()), escapeCell(c.Short))
	}
	b.WriteString("\n")
	link := func(name string) string {
		return "#" + anchor(strings.ReplaceAll(strings.TrimSuffix(name, ".md"), "_", " "))
	}
	for _, c := range cmds {
		c.DisableAutoGenTag = true // no generation date: the output must be reproducible
		var section bytes.Buffer
		if err := doc.GenMarkdownCustom(c, &section, link); err != nil {
			return fmt.Errorf("generate the reference of %s: %w", c.CommandPath(), err)
		}
		for line := range strings.Lines(section.String()) {
			if strings.HasPrefix(line, "* [dlm completion](") { // see the walk above
				continue
			}
			b.WriteString(line)
		}
		b.WriteString("\n")
	}
	if _, err := w.Write(b.Bytes()); err != nil {
		return fmt.Errorf("write the reference: %w", err)
	}
	return nil
}

// anchor is the GitHub heading anchor of a heading.
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), " ", "-")
}

func escapeCell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
