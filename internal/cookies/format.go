package cookies

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/sabadia/dlm-server/internal/domain"
)

// Format is a cookie file format.
type Format string

// Supported formats.
const (
	// FormatJSON is a JSON array of cookie objects (the shape of
	// domain.Cookie; browser-extension exports with expirationDate and
	// sameSite values such as "no_restriction" are read too).
	FormatJSON Format = "json"
	// FormatNetscape is the tab-separated cookies.txt format read by curl,
	// wget and yt-dlp.
	FormatNetscape Format = "netscape"
)

// ParseFormat parses a format name; "" selects FormatJSON.
func ParseFormat(s string) (Format, error) {
	switch Format(strings.ToLower(s)) {
	case "", FormatJSON:
		return FormatJSON, nil
	case FormatNetscape:
		return FormatNetscape, nil
	default:
		return "", domain.InvalidArgument("cookies: unknown format %q (want json or netscape)", s)
	}
}

// DetectFormat guesses the format of data: JSON starts with '[' or '{'.
func DetectFormat(data []byte) Format {
	t := bytes.TrimSpace(data)
	if len(t) > 0 && (t[0] == '[' || t[0] == '{') {
		return FormatJSON
	}
	return FormatNetscape
}

// Encode writes cookies in the given format.
func Encode(format Format, cookies []*domain.Cookie) ([]byte, error) {
	switch format {
	case FormatJSON:
		return EncodeJSON(cookies)
	case FormatNetscape:
		return EncodeNetscape(cookies), nil
	default:
		return nil, domain.InvalidArgument("cookies: unknown format %q", string(format))
	}
}

// EncodeJSON writes cookies as an indented JSON array.
func EncodeJSON(cookies []*domain.Cookie) ([]byte, error) {
	if cookies == nil {
		cookies = []*domain.Cookie{}
	}
	data, err := json.MarshalIndent(cookies, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("cookies: encode json: %w", err)
	}
	return append(data, '\n'), nil
}

// maxExpirationSeconds is 9999-12-31T23:59:59Z, the latest time that
// round-trips through RFC 3339.
const maxExpirationSeconds = 253402300799

const (
	netscapeHeader     = "# Netscape HTTP Cookie File\n# Generated by dlm. This file contains secrets: keep it private.\n\n"
	netscapeHTTPOnly   = "#HttpOnly_"
	netscapeFieldCount = 7
)

// EncodeNetscape writes cookies in the Netscape cookies.txt format. A
// cookie whose name or value contains a tab or line break cannot be
// represented (and would let a value inject extra lines), so it is left out.
func EncodeNetscape(cookies []*domain.Cookie) []byte {
	var b bytes.Buffer
	b.WriteString(netscapeHeader)
	for _, c := range cookies {
		if strings.ContainsAny(c.Name+c.Value, "\t\r\n") {
			continue
		}
		d := c.Domain
		if !c.HostOnly {
			d = "." + d
		}
		if c.HTTPOnly {
			d = netscapeHTTPOnly + d
		}
		var expires int64
		if c.ExpiresAt != nil && !c.ExpiresAt.IsZero() {
			expires = c.ExpiresAt.Unix()
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%d\t%s\t%s\n",
			d, netscapeBool(!c.HostOnly), c.Path, netscapeBool(c.Secure), expires, c.Name, c.Value)
	}
	return b.Bytes()
}

func netscapeBool(v bool) string {
	if v {
		return "TRUE"
	}
	return "FALSE"
}

// WriteTempNetscape writes cookies to a new Netscape file (mode 0600) in dir
// (the OS temp directory when empty) for tools that read cookies from a file,
// such as yt-dlp. The caller must call cleanup, which removes the file.
func WriteTempNetscape(dir string, cookies []*domain.Cookie) (path string, cleanup func(), err error) {
	f, err := os.CreateTemp(dir, "dlm-cookies-*.txt") // created with mode 0600
	if err != nil {
		return "", nil, fmt.Errorf("cookies: create temporary cookie file: %w", err)
	}
	path = f.Name()
	remove := func() { _ = os.Remove(path) } // best effort: the file is in a temp directory
	if _, err := f.Write(EncodeNetscape(cookies)); err != nil {
		_ = f.Close()
		remove()
		return "", nil, fmt.Errorf("cookies: write temporary cookie file: %w", err)
	}
	if err := f.Close(); err != nil {
		remove()
		return "", nil, fmt.Errorf("cookies: write temporary cookie file: %w", err)
	}
	return filepath.Clean(path), remove, nil
}

// Parsed is one cookie read from a file, or the reason it was rejected.
type Parsed struct {
	// Index is the 1-based position (JSON array element or file line).
	Index  int
	Cookie *domain.Cookie
	Err    error
}

// Decode reads cookies in the given format. A malformed element yields a
// Parsed with Err set; a malformed document is an error.
func Decode(format Format, data []byte) ([]Parsed, error) {
	switch format {
	case FormatJSON:
		return DecodeJSON(data)
	case FormatNetscape:
		return DecodeNetscape(data), nil
	default:
		return nil, domain.InvalidArgument("cookies: unknown format %q", string(format))
	}
}

// jsonCookie is the lenient import shape: domain.Cookie plus the field names
// of browser cookie exports.
type jsonCookie struct {
	Domain         string          `json:"domain"`
	Name           string          `json:"name"`
	Value          string          `json:"value"`
	Path           string          `json:"path"`
	PartitionKey   json.RawMessage `json:"partitionKey"`
	Secure         bool            `json:"secure"`
	HTTPOnly       bool            `json:"httpOnly"`
	SameSite       string          `json:"sameSite"`
	HostOnly       *bool           `json:"hostOnly"`
	ExpiresAt      *time.Time      `json:"expiresAt"`
	ExpirationDate *float64        `json:"expirationDate"`
	Session        bool            `json:"session"`
}

// DecodeJSON reads a JSON array of cookies, or an object with a "cookies"
// array.
func DecodeJSON(data []byte) ([]Parsed, error) {
	var items []json.RawMessage
	trimmed := bytes.TrimSpace(data)
	if len(trimmed) > 0 && trimmed[0] == '{' {
		var wrapper struct {
			Cookies []json.RawMessage `json:"cookies"`
		}
		if err := json.Unmarshal(trimmed, &wrapper); err != nil {
			return nil, domain.InvalidArgument("cookies: invalid JSON: %v", err)
		}
		items = wrapper.Cookies
	} else if err := json.Unmarshal(trimmed, &items); err != nil {
		return nil, domain.InvalidArgument("cookies: invalid JSON: want an array of cookies: %v", err)
	}
	out := make([]Parsed, len(items))
	for i, raw := range items {
		out[i] = Parsed{Index: i + 1}
		var jc jsonCookie
		if err := json.Unmarshal(raw, &jc); err != nil {
			out[i].Err = fmt.Errorf("invalid cookie: %w", err)
			continue
		}
		out[i].Cookie = jc.toDomain()
	}
	return out, nil
}

func (jc jsonCookie) toDomain() *domain.Cookie {
	c := &domain.Cookie{
		Domain:       jc.Domain,
		Name:         jc.Name,
		Value:        jc.Value,
		Path:         jc.Path,
		PartitionKey: partitionKeyString(jc.PartitionKey),
		Secure:       jc.Secure,
		HTTPOnly:     jc.HTTPOnly,
		SameSite:     normalizeSameSite(jc.SameSite),
		ExpiresAt:    jc.ExpiresAt,
	}
	if jc.HostOnly != nil {
		c.HostOnly = *jc.HostOnly
	} else {
		c.HostOnly = !strings.HasPrefix(jc.Domain, ".")
	}
	if c.ExpiresAt == nil && jc.ExpirationDate != nil && !jc.Session && *jc.ExpirationDate > 0 {
		sec := min(*jc.ExpirationDate, maxExpirationSeconds) // bounded so the int64 conversion cannot overflow
		t := time.UnixMilli(int64(sec * 1000)).UTC()
		c.ExpiresAt = &t
	}
	return c
}

// partitionKeyString accepts a plain string or the {"topLevelSite": "..."}
// object of Chromium exports.
func partitionKeyString(raw json.RawMessage) string {
	if len(raw) == 0 {
		return ""
	}
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	var obj struct {
		TopLevelSite string `json:"topLevelSite"`
	}
	if json.Unmarshal(raw, &obj) == nil {
		return obj.TopLevelSite
	}
	return ""
}

// normalizeSameSite maps browser export values onto lax/strict/none; an
// unknown value is kept so that validation rejects it.
func normalizeSameSite(s string) string {
	switch strings.ToLower(s) {
	case "", "unspecified":
		return ""
	case "no_restriction":
		return "none"
	default:
		return strings.ToLower(s)
	}
}

// DecodeNetscape reads a Netscape cookies.txt file. Lines starting with '#'
// are comments, except "#HttpOnly_" which marks an HttpOnly cookie.
func DecodeNetscape(data []byte) []Parsed {
	var out []Parsed
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	for line := 1; sc.Scan(); line++ {
		text := strings.TrimRight(sc.Text(), "\r")
		httpOnly := false
		if rest, ok := strings.CutPrefix(text, netscapeHTTPOnly); ok {
			text, httpOnly = rest, true
		}
		if strings.TrimSpace(text) == "" || strings.HasPrefix(text, "#") {
			continue
		}
		c, err := parseNetscapeLine(text, httpOnly)
		out = append(out, Parsed{Index: line, Cookie: c, Err: err})
	}
	if err := sc.Err(); err != nil {
		out = append(out, Parsed{Err: fmt.Errorf("read: %w", err)})
	}
	return out
}

func parseNetscapeLine(text string, httpOnly bool) (*domain.Cookie, error) {
	f := strings.SplitN(text, "\t", netscapeFieldCount)
	if len(f) == netscapeFieldCount-1 {
		f = append(f, "") // empty value: the trailing tab was trimmed
	}
	if len(f) != netscapeFieldCount {
		return nil, fmt.Errorf("want %d tab-separated fields, got %d", netscapeFieldCount, len(f))
	}
	expires, err := strconv.ParseInt(strings.TrimSpace(f[4]), 10, 64)
	if err != nil {
		return nil, fmt.Errorf("invalid expiry %q", f[4])
	}
	c := &domain.Cookie{
		Domain:   f[0],
		HostOnly: !strings.EqualFold(f[1], "TRUE"),
		Path:     f[2],
		Secure:   strings.EqualFold(f[3], "TRUE"),
		HTTPOnly: httpOnly,
		Name:     f[5],
		Value:    f[6],
	}
	if expires > 0 {
		t := time.Unix(expires, 0).UTC()
		c.ExpiresAt = &t
	}
	return c, nil
}
